"""Writes the small plot files the React pages use (search, plot details, dashboards), from data/plots.geojson.

    python -I tools/make_index.py

data/plots.geojson (12 MB) is what the 3D map needs. The other pages need far less:
    data/plots_index.json     every plot's properties as rows (about 1 MB), no outlines; repeated text in `dict`
    data/outlines/<A..X>.json the outline of every plot in one block, {id: [[lon, lat], ...]}, 6 decimals
make_data.py runs this at the end, so the files stay in step with the map.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
FIELDS = ['id', 'no', 'num', 'sub', 'blk', 'size', 'type', 'status', 'dev', 'built', 'storeys', 'height', 'marla', 'area',
          'lat', 'lon', 'bshare', 'src', 'conf', 'layout', 'numsrc']


def main():
    plots = json.load(open(os.path.join(DATA, 'plots.geojson'), encoding='utf-8'))['features']
    rows, outlines = [], {}
    for f in plots:
        p = f['properties']
        blk = p['block'].replace('Block ', '')
        rows.append([p['id'], p['plot_no'], p.get('plot_number'), p.get('sub_block'), blk, p['size'], p['type'], p['status'],
                     p['dev_class'], 1 if p['built'] else 0, p.get('storeys') or 0, p.get('height') or 0, p.get('marla'),
                     p.get('area_m2'), round(p['lat'], 6), round(p['lon'], 6), p.get('built_share_150m'), p.get('source'),
                     p.get('confidence'), p.get('layout'), p.get('number_source')])
        g = f['geometry']
        ring = g['coordinates'][0] if g['type'] == 'Polygon' else g['coordinates'][0][0]
        outlines.setdefault(blk, {})[p['id']] = [[round(x, 6), round(y, 6)] for x, y in ring[:-1]]
    os.makedirs(os.path.join(DATA, 'outlines'), exist_ok=True)
    # text that repeats (size, status, source...) is stored once in `dict` and referred to by its position
    coded = {'size', 'type', 'status', 'dev', 'src', 'conf', 'layout', 'numsrc', 'sub'}
    dicts = {k: [] for k in coded}
    for r in rows:
        for i, k in enumerate(FIELDS):
            if k in coded and r[i] is not None:
                d = dicts[k]
                if r[i] not in d: d.append(r[i])
                r[i] = d.index(r[i])
    idx = {'fields': FIELDS, 'dict': dicts, 'rows': rows, 'count': len(rows),
           'note': 'Generated by tools/make_index.py from plots.geojson. Status and storeys are sample values until society records arrive.'}
    with open(os.path.join(DATA, 'plots_index.json'), 'w', encoding='utf-8') as fh:
        json.dump(idx, fh, ensure_ascii=False, separators=(',', ':'))
    for blk, o in outlines.items():
        with open(os.path.join(DATA, 'outlines', blk + '.json'), 'w', encoding='utf-8') as fh:
            json.dump(o, fh, separators=(',', ':'))
    print(f'{len(rows)} plots -> plots_index.json ({os.path.getsize(os.path.join(DATA, "plots_index.json")) // 1024} KB), '
          f'outlines for blocks {", ".join(sorted(outlines))}')


if __name__ == '__main__':
    sys.exit(main())
